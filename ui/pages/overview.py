"""Page 1 - Overview: KPIs and charts computed from the database."""

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from config import settings
from database import repository
from database.connection import fetch_all
from ui.components import (
    MUTED_GRAY,
    SEQUENTIAL_BLUE,
    SERIES_COLORS,
    STATUS_COLORS,
    STATUS_STYLE,
    kpi_card,
    page_header,
    style_figure,
)
from utils.validators import format_inr


def render() -> None:
    page_header(settings.APP_NAME, settings.APP_SUBTITLE)

    kpis = repository.get_dashboard_kpis()
    cards = [
        ("Procurement requests", kpis["total_requests"], "all time"),
        ("Active orders", kpis["active_orders"], "confirmed or at risk"),
        ("Active disruptions", kpis["active_disruptions"], "open supply risks"),
        ("Units at risk", f"{kpis['units_at_risk']:,}", "shortage from open disruptions"),
        ("Recovery plans", kpis["recovery_plans"], "generated by the agent"),
        ("Est. recovery cost", format_inr(kpis["recovery_cost"]), "proposed + approved"),
    ]
    for column, (label, value, hint) in zip(st.columns(6), cards):
        with column:
            kpi_card(label, value, hint)

    st.write("")
    left, right = st.columns(2)
    with left:
        with st.container(border=True):
            st.markdown("**Orders by status**")
            _orders_by_status_chart()
        with st.container(border=True):
            st.markdown("**Procurement cost by supplier** (active commitments)")
            _cost_breakdown_chart()
    with right:
        with st.container(border=True):
            st.markdown("**Supplier reliability**")
            _supplier_reliability_chart()
        with st.container(border=True):
            st.markdown("**Disruptions detected per day**")
            _disruption_trend_chart()


def _orders_by_status_chart() -> None:
    orders = repository.list_orders()
    if not orders:
        st.info("No orders yet.")
        return
    counts = pd.DataFrame(orders)["status"].value_counts()
    colors = [STATUS_COLORS[STATUS_STYLE.get(status, ("neutral", ""))[0]] for status in counts.index]
    fig = go.Figure(go.Bar(
        x=counts.values, y=[s.replace("_", " ").title() for s in counts.index], orientation="h",
        marker=dict(color=colors, cornerradius=4), text=counts.values, textposition="outside",
        hovertemplate="%{y}: %{x} order(s)<extra></extra>",
    ))
    fig.update_xaxes(dtick=1, title="Orders")
    st.plotly_chart(style_figure(fig, 220), width="stretch")


def _supplier_reliability_chart() -> None:
    suppliers = fetch_all("SELECT name, reliability, approved FROM suppliers ORDER BY reliability")
    frame = pd.DataFrame(suppliers)
    fig = go.Figure()
    for approved, name, color in [(1, "Approved", SEQUENTIAL_BLUE), (0, "Not approved", MUTED_GRAY)]:
        subset = frame[frame["approved"] == approved]
        fig.add_bar(x=subset["reliability"] * 100, y=subset["name"], orientation="h", name=name,
                    marker=dict(color=color, cornerradius=4),
                    hovertemplate="%{y}: %{x:.0f}% reliability<extra>" + name + "</extra>")
    fig.add_vline(x=settings.MIN_SUPPLIER_RELIABILITY * 100, line_dash="dot", line_color=STATUS_COLORS["critical"],
                  annotation_text=f"Minimum {settings.MIN_SUPPLIER_RELIABILITY:.0%}", annotation_position="top")
    fig.update_xaxes(range=[60, 100], title="Reliability (%)")
    fig.update_layout(barmode="overlay")
    st.plotly_chart(style_figure(fig, 560), width="stretch")


def _cost_breakdown_chart() -> None:
    rows = fetch_all(
        """
        SELECT s.name AS supplier, SUM(c.committed_qty * c.unit_price) AS cost
        FROM supplier_commitments c JOIN suppliers s ON s.id = c.supplier_id
        WHERE c.status NOT IN ('CANCELLED', 'REPLACED', 'DELIVERED') AND c.committed_qty > 0
        GROUP BY s.name ORDER BY cost
        """
    )
    if not rows:
        st.info("No active supplier commitments.")
        return
    frame = pd.DataFrame(rows)
    fig = go.Figure(go.Bar(
        x=frame["cost"], y=frame["supplier"], orientation="h", marker=dict(color=SEQUENTIAL_BLUE, cornerradius=4),
        text=[format_inr(value) for value in frame["cost"]], textposition="outside",
        hovertemplate="%{y}: ₹%{x:,.0f}<extra></extra>",
    ))
    fig.update_xaxes(title="Committed cost (₹)")
    st.plotly_chart(style_figure(fig, 260), width="stretch")


def _disruption_trend_chart() -> None:
    rows = fetch_all("SELECT DATE(detected_at) AS day, disruption_type, COUNT(*) AS n FROM disruptions "
                     "GROUP BY day, disruption_type ORDER BY day")
    if not rows:
        st.info("No disruptions detected yet. Use the Simulation Lab to create supplier events.")
        return
    frame = pd.DataFrame(rows)
    fig = go.Figure()
    # Fixed colour per disruption type (colour follows the entity, never its rank).
    for index, kind in enumerate(["QUANTITY_REDUCED", "CANCELLED", "DELAYED", "PRICE_INCREASE"]):
        subset = frame[frame["disruption_type"] == kind]
        if subset.empty:
            continue
        fig.add_bar(x=subset["day"], y=subset["n"], name=kind.replace("_", " ").title(),
                    marker=dict(color=SERIES_COLORS[index], cornerradius=4, line=dict(width=2, color="rgba(0,0,0,0)")),
                    hovertemplate="%{x}: %{y}<extra>" + kind.replace("_", " ").title() + "</extra>")
    fig.update_layout(barmode="stack")
    fig.update_yaxes(dtick=1, title="Disruptions")
    fig.update_xaxes(type="category")
    st.plotly_chart(style_figure(fig, 260), width="stretch")
